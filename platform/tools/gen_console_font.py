# Generates platform/src/console_font.h: an 8x8 bitmap font (ASCII 32..126) for the text console that stands in
# for libctru's touch-screen console. Drawn from DejaVu Sans Mono (Bitstream Vera licence: free to embed).
#
#   python3 platform/tools/gen_console_font.py platform/src/console_font.h [font.ttf]
import sys

from PIL import Image, ImageDraw, ImageFont

OUT = sys.argv[1]
TTF = sys.argv[2] if len(sys.argv) > 2 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
font = ImageFont.truetype(TTF, 9)
ascent, _ = font.getmetrics()

rows = []
for c in range(32, 127):
    im = Image.new("1", (8, 8), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"   # FreeType's hinted monochrome rendering: crisp at 8 px
    w = font.getlength(chr(c))
    # capitals on rows 0..6, the baseline under row 6: descenders get row 7
    d.text((int((8 - w) / 2), 7 - ascent), chr(c), fill=1, font=font)
    bits = []
    for y in range(8):
        b = 0
        for x in range(8):
            if im.getpixel((x, y)):
                b |= 0x80 >> x
        bits.append(b)
    rows.append((c, bits))

with open(OUT, "w") as f:
    f.write("// console_font.h - generated by platform/tools/gen_console_font.py from DejaVu Sans Mono\n")
    f.write("// (Bitstream Vera licence). 8x8 glyphs for ASCII 32..126, one byte per row, bit 7 = leftmost pixel.\n")
    f.write("#pragma once\n#include <stdint.h>\n\nstatic const uint8_t kConsoleFont[95][8] = {\n")
    for c, bits in rows:
        ch = chr(c).replace("\\", "backslash")
        f.write("    {%s},  // %s\n" % (", ".join("0x%02X" % b for b in bits), ch))
    f.write("};\n")
